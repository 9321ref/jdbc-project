--1.Display all first_name and  related department_name
SELECT * FROM EMPLOYEES;

SELECT FIRST_NAME,DEPARTMENT_NAME
FROM EMPLOYEES E JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

--Order the list based on firstname asc  ortak paydada olan
SELECT FIRST_NAME,DEPARTMENT_NAME
FROM EMPLOYEES E INNER JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
ORDER BY FIRST_NAME ASC;


--2.Display all first_name and department_name including the  employee without department(null)
SELECT FIRST_NAME,DEPARTMENT_NAME
FROM EMPLOYEES E LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
ORDER BY FIRST_NAME ASC;


--sagda ki table dan solda ki table a --> DEPARTMENTS <--> EMPLOYEES
SELECT FIRST_NAME,DEPARTMENT_NAME
FROM DEPARTMENTS D RIGHT JOIN  EMPLOYEES E
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
ORDER BY FIRST_NAME ASC;


--3.Display all first_name and department_name including the department without employee

SELECT * FROM DEPARTMENTS;

SELECT FIRST_NAME,E.DEPARTMENT_ID,DEPARTMENT_NAME
FROM EMPLOYEES E RIGHT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;


--4.How many employee we have for each department name

SELECT DEPARTMENT_NAME,COUNT(*)
FROM EMPLOYEES E JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY DEPARTMENT_NAME;


--5.Display all firstname and department name including the department without employees(null)
-- and also employees without the department(null)

SELECT FIRST_NAME,DEPARTMENT_NAME
FROM EMPLOYEES E FULL JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

